"""scripts/release.py: the prepare / open-Unreleased bookkeeping around a release."""

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("release", ROOT / "scripts" / "release.py")
assert spec is not None and spec.loader is not None
release = importlib.util.module_from_spec(spec)
spec.loader.exec_module(release)

CHANGELOG = """# Changelog

## [Unreleased]

### Fixed

- A fixed thing (#9).

## v1.2.0 - 2026-01-01

### Added

- Older thing.
"""


def make_tree(tmp: Path, version: str = "1.2.0", changelog: str = CHANGELOG) -> Path:
    (tmp / "src/tplink_admin").mkdir(parents=True)
    (tmp / "docs").mkdir()
    (tmp / "pyproject.toml").write_text(f'[project]\nname = "x"\nversion = "{version}"\n')
    (tmp / "src/tplink_admin/__init__.py").write_text(f'"""x"""\n\n__version__ = "{version}"\n')
    (tmp / "CHANGELOG.md").write_text(changelog)
    (tmp / "README.md").write_text(
        f"[![Version](https://img.shields.io/badge/release-v{version}-blue.svg)]"
        f"(https://github.com/o/r/releases/tag/v{version})\n")
    (tmp / "docs/openapi.json").write_text(json.dumps({"info": {"version": version}}))
    return tmp


class ReleaseScriptTests(unittest.TestCase):
    def tree(self, **kwargs):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        return make_tree(Path(tmp.name), **kwargs)

    def test_prepare_finalizes_unreleased_and_bumps_every_version(self):
        root = self.tree()
        release.prepare(root, "1.3.0", "2026-10-26", regenerate=False)
        changelog = (root / "CHANGELOG.md").read_text()
        self.assertNotIn("[Unreleased]", changelog)
        self.assertIn("## v1.3.0 - 2026-10-26\n\n### Fixed\n\n- A fixed thing (#9).", changelog)
        self.assertEqual(release.current_version(root), "1.3.0")
        self.assertEqual(release.package_version(root), "1.3.0")
        readme = (root / "README.md").read_text()
        self.assertIn("release-v1.3.0-blue", readme)
        self.assertIn("releases/tag/v1.3.0", readme)
        # openapi.json is regenerated by the real command; simulate it here.
        (root / "docs/openapi.json").write_text(json.dumps({"info": {"version": "1.3.0"}}))
        self.assertEqual(release.check(root, "1.3.0"), [])

    def test_prepare_refuses_unsafe_inputs(self):
        cases = {
            "not semver": ("1.3", CHANGELOG),
            "not greater": ("1.2.0", CHANGELOG),
            "downgrade": ("1.1.9", CHANGELOG),
            "no unreleased section": ("1.3.0", CHANGELOG.replace("## [Unreleased]", "## Notes")),
            "empty unreleased": ("1.3.0", "# Changelog\n\n## [Unreleased]\n\n## v1.2.0 - 2026-01-01\n\n- x\n"),
            "duplicate version": ("1.3.0", CHANGELOG + "\n## v1.3.0 - 2026-02-02\n\n- y\n"),
        }
        for label, (version, changelog) in cases.items():
            with self.subTest(label):
                root = self.tree(changelog=changelog)
                before = {p: p.read_text() for p in root.rglob("*") if p.is_file()}
                with self.assertRaises(release.ReleaseError):
                    release.prepare(root, version, "2026-10-26", regenerate=False)
                after = {p: p.read_text() for p in root.rglob("*") if p.is_file()}
                self.assertEqual(before, after, "a refused prepare must not touch files")

    def test_prepare_is_all_or_nothing_when_regeneration_fails(self):
        from unittest.mock import patch
        root = self.tree()
        before = {p: p.read_bytes() for p in root.rglob("*") if p.is_file()}
        with patch.object(release, "regenerate_artifacts", side_effect=RuntimeError("generator failed")), \
                self.assertRaises(RuntimeError):
            release.prepare(root, "1.3.0", "2026-10-26")
        self.assertEqual(before, {p: p.read_bytes() for p in root.rglob("*") if p.is_file()})

    def test_open_adds_one_empty_unreleased_section(self):
        root = self.tree()
        release.prepare(root, "1.3.0", "2026-10-26", regenerate=False)
        release.open_unreleased(root)
        changelog = (root / "CHANGELOG.md").read_text()
        self.assertTrue(changelog.startswith("# Changelog\n\n## [Unreleased]\n\n## v1.3.0 - 2026-10-26\n"))
        with self.assertRaises(release.ReleaseError):
            release.open_unreleased(root)

    def test_check_reports_each_mismatch(self):
        root = self.tree()
        problems = release.check(root, "1.3.0")
        joined = "\n".join(problems)
        for needle in ("pyproject.toml is 1.2.0", "tplink_admin.__version__ is 1.2.0", "no `## v1.3.0",
                       "unreleased entries", "docs/openapi.json version is 1.2.0", "README.md release badge"):
            self.assertIn(needle, joined)

    def test_notes_are_the_version_section(self):
        root = self.tree()
        notes = release.notes(root, "1.2.0")
        self.assertTrue(notes.startswith("# tplinkctl v1.2.0\n\n### Added\n\n- Older thing."))
        self.assertIn("https://pypi.org/project/tplink-admin-cli/1.2.0/", notes)
        self.assertNotIn("A fixed thing", notes)
        with self.assertRaises(release.ReleaseError):
            release.notes(root, "9.9.9")

    def test_real_repository_is_consistent_for_its_version(self):
        version = release.current_version(ROOT)
        self.assertEqual(release.package_version(ROOT), version)
        problems = release.check(ROOT, version)
        # Between releases the only expected gap is pending Unreleased work.
        self.assertTrue(all("unreleased entries" in p for p in problems), problems)
        self.assertIsNotNone(release.notes(ROOT, version))


if __name__ == "__main__":
    unittest.main()
